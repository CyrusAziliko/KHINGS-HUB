function createReportId(){

  const date = new Date();

  return (
    "RPT-" +
    date.getFullYear() +
    String(date.getMonth()+1).padStart(2,"0") +
    String(date.getDate()).padStart(2,"0") +
    "-" +
    Math.floor(Math.random()*900+100)
  );

}



function createPDF(title){

  if(!window.jspdf){

    alert(
      "PDF library not loaded"
    );

    return null;
  }


  const {
    jsPDF
  } = window.jspdf;


  const doc = new jsPDF();


  const reportId =
  createReportId();



  doc.setFontSize(20);

  doc.text(
    "KHING'S HUB",
    20,
    20
  );


  doc.setFontSize(11);

  doc.text(
    "Enterprise Mining Management System",
    20,
    28
  );



  doc.setFontSize(16);

  doc.text(
    title,
    20,
    45
  );



  doc.setFontSize(10);

  doc.text(
    `Report ID: ${reportId}`,
    20,
    55
  );


  doc.text(
    `Generated: ${new Date().toLocaleString()}`,
    20,
    62
  );


  return doc;

}





function addFooter(doc){

  const pages =
  doc.getNumberOfPages();


  for(
    let i=1;
    i<=pages;
    i++
  ){

    doc.setPage(i);


    doc.setFontSize(9);


    doc.text(
      `Generated by KHING'S HUB EMS | Page ${i}/${pages}`,
      20,
      290
    );

  }

}



function drawTable(
  doc,
  headers,
  rows,
  startY=90
){

  let y=startY;


  doc.setFontSize(10);


  doc.setFont(undefined,"bold");


  doc.text(
    headers.join("     "),
    20,
    y
  );

  y+=8;


  doc.setFont(undefined,"normal");



  rows.forEach(row=>{


    if(y>270){

      doc.addPage();

      y=20;

    }


    doc.text(
      row.join("     ").substring(0,120),
      20,
      y
    );

    y+=7;


  });

}



function generateExecutiveSummary(type, data){

  let summary = "";
  let risk = "LOW";
  let recommendation = "";



  switch(type){


    case "equipment":{

      const total = data.length;

      const offline =
      data.filter(
        e => String(e.status || "").toLowerCase() === "offline"
      ).length;


      const maintenance =
      data.filter(
        e => String(e.status || "").toLowerCase() === "maintenance"
      ).length;



      const offlineRate =
      total ? (offline / total) * 100 : 0;



      if(offlineRate > 30){

        risk = "HIGH";

      }
      else if(maintenance > total * 0.2){

        risk = "MEDIUM";

      }



      summary =
      `The mining operation currently manages ${total} registered equipment assets. ` +
      `${offline} assets are offline and ${maintenance} require maintenance attention.`;


      recommendation =
      risk === "HIGH"
      ? "Immediate equipment inspection is recommended."
      : risk === "MEDIUM"
      ? "Maintenance activities should be reviewed."
      : "Equipment condition is stable. Continue preventive maintenance.";


      break;

    }





    case "safety":{


      const critical =
      data.filter(
        i =>
        ["critical","high"]
        .includes(
          String(i.severity || "").toLowerCase()
        )
      ).length;



      const active =
      data.filter(
        i =>
        String(i.status || "").toLowerCase()
        ===
        "active"
      ).length;



      if(critical > 5){

        risk="HIGH";

      }
      else if(critical > 0){

        risk="MEDIUM";

      }



      summary =
      `${data.length} safety incidents have been recorded. `+
      `${critical} incidents are classified as high priority and ${active} remain active.`;


      recommendation =
      risk==="HIGH"
      ?
      "Immediate safety investigation is required."
      :
      "Continue monitoring safety compliance.";


      break;

    }





    case "tickets":{


      const open =
      data.filter(
        t =>
        String(t.status || "")
        .toLowerCase()
        ===
        "open"
      ).length;



      const critical =
      data.filter(
        t =>
        ["critical","high"]
        .includes(
          String(t.priority || "")
          .toLowerCase()
        )
      ).length;



      if(critical > 10){

        risk="HIGH";

      }
      else if(open > data.length * 0.3){

        risk="MEDIUM";

      }



      summary =
      `${data.length} support tickets are currently tracked. `+
      `${open} remain unresolved with ${critical} high priority requests.`;


      recommendation =
      risk==="HIGH"
      ?
      "Prioritize critical support requests."
      :
      "Ticket workload is within acceptable range.";


      break;

    }





    case "workforce":{


      const departments =
      new Set(
        data.map(
          w=>w.department
        )
        .filter(Boolean)
      ).size;


      summary =
      `The organization has ${data.length} registered workers across ${departments} departments.`;



      recommendation =
      "Maintain workforce allocation and monitor operational coverage.";


      risk="LOW";


      break;

    }


  }



  return {
    summary,
    risk,
    recommendation

  };


}



function generateEquipmentReport(data){


const doc =
createPDF(
"Equipment Operations Report"
);


if(!doc)return;


doc.setFontSize(12);


const insight =
generateExecutiveSummary(
"equipment",
data
);


doc.text(
"EXECUTIVE SUMMARY",
20,
80
);

doc.setFontSize(10);

doc.text(
insight.summary,
20,
90,
{
maxWidth:170
}
);

doc.text(
`Risk Level: ${insight.risk}`,
20,
110
);

doc.text(
`Recommendation: ${insight.recommendation}`,
20,
120,
{
maxWidth:170
}
);



drawTable(

doc,

[
"Name",
"Status",
"Location"
],


data.map(item=>[

item.name || "-",

item.status || "-",

item.location || "-"

])

);



addFooter(doc);


doc.save(
"KHINGS_HUB_Equipment_Report.pdf"
);


}







