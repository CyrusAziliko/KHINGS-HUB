export async function loadReports() {
  const root = document.getElementById("reports-root");
  if (!root) {
    console.warn("Reports root container missing");
    return;
  }

  root.innerHTML = `
    <div class="card glass">
      <h2 class="report-header">📑 Enterprise Report Center</h2>
      <p class="muted">Generate operational intelligence reports for mining operations.</p>
      <div class="report-grid" id="reports-grid">Loading reports...</div>
    </div>
  `;

  // Fetch required data from existing tables only
  const [{ data: equipment, error: equipmentError },
    { data: safetyIncidents, error: safetyError },
    { data: tickets, error: ticketsError },
    { data: profiles, error: profilesError }] = await Promise.all([
    supabase
      .from("equipment")
      .select("id,name,type,serial_number,status,location,created_at"),
    supabase
      .from("safety_incidents")
      .select("id,title,severity,status,created_at"),
    supabase
      .from("tickets")
      .select("id,status,priority,created_at"),
    supabase
      .from("profiles")
      .select("id,full_name,role,department")
      .limit(10000)
  ]);

  if (equipmentError || safetyError || ticketsError || profilesError) {
    console.error("Reports load failed", { equipmentError, safetyError, ticketsError, profilesError });
    root.innerHTML = `
      <div class="card glass">
        <h2 class="report-header">📑 Enterprise Report Center</h2>
        <p class="muted">Unable to load report data.</p>
      </div>
    `;
    return;
  }

  const equipmentRows = equipment || [];
  const safetyRows = safetyIncidents || [];
  const ticketRows = tickets || [];
  const profileRows = profiles || [];

  // Equipment metrics
  const totalEquipment = equipmentRows.length;
  const availableEquipment = equipmentRows.filter(
    (e) => String(e.status || "").toLowerCase() === "available"
  ).length;
  const maintenanceEquipment = equipmentRows.filter(
    (e) => String(e.status || "").toLowerCase() === "maintenance"
  ).length;
  const offlineEquipment = equipmentRows.filter(
    (e) => String(e.status || "").toLowerCase() === "offline"
  ).length;

  // Safety metrics
  const totalIncidents = safetyRows.length;
  const activeIncidents = safetyRows.filter(
    (s) => String(s.status || "").toLowerCase() === "active"
  ).length;
  const criticalHighIncidents = safetyRows.filter((s) => {
    const sev = String(s.severity || "").toLowerCase();
    return sev === "critical" || sev === "high";
  }).length;

  // Ticket metrics
  const totalTickets = ticketRows.length;
  const openTickets = ticketRows.filter(
    (t) => String(t.status || "").toLowerCase() === "open"
  ).length;
  const resolvedTickets = ticketRows.filter(
    (t) => String(t.status || "").toLowerCase() === "resolved"
  ).length;

  // Workforce metrics
  const totalWorkers = profileRows.length;
  const departments = new Set(
    profileRows
      .map((p) => (p.department ? String(p.department).trim() : ""))
      .filter(Boolean)
  );
  const departmentsCount = departments.size;

  root.innerHTML = `
    <div class="card glass">
      <h2 class="report-header">📑 Enterprise Report Center</h2>
      <p class="muted">Generate operational intelligence reports for mining operations.</p>

      <div class="report-grid">

        <div class="report-card">
          <div class="report-icon">🚜</div>
          <div class="report-title">Equipment Report</div>
          <div class="report-values">
            <div class="report-value"><span>Total equipment</span><strong>${totalEquipment}</strong></div>
            <div class="report-value"><span>Available equipment</span><strong>${availableEquipment}</strong></div>
            <div class="report-value"><span>Maintenance equipment</span><strong>${maintenanceEquipment}</strong></div>
            <div class="report-value"><span>Offline equipment</span><strong>${offlineEquipment}</strong></div>
          </div>
          <button class="report-button" type="button">Generate Report</button>
        </div>

        <div class="report-card">
          <div class="report-icon">⚠️</div>
          <div class="report-title">Safety Report</div>
          <div class="report-values">
            <div class="report-value"><span>Total incidents</span><strong>${totalIncidents}</strong></div>
            <div class="report-value"><span>Active incidents</span><strong>${activeIncidents}</strong></div>
            <div class="report-value"><span>Critical/High severity incidents</span><strong>${criticalHighIncidents}</strong></div>
          </div>
          <button class="report-button" type="button">Generate Report</button>
        </div>

        <div class="report-card">
          <div class="report-icon">🎫</div>
          <div class="report-title">Ticket Report</div>
          <div class="report-values">
            <div class="report-value"><span>Total tickets</span><strong>${totalTickets}</strong></div>
            <div class="report-value"><span>Open tickets</span><strong>${openTickets}</strong></div>
            <div class="report-value"><span>Resolved tickets</span><strong>${resolvedTickets}</strong></div>
          </div>
          <button class="report-button" type="button">Generate Report</button>
        </div>

        <div class="report-card">
          <div class="report-icon">👷</div>
          <div class="report-title">Workforce Report</div>
          <div class="report-values">
            <div class="report-value"><span>Total workers</span><strong>${totalWorkers}</strong></div>
            <div class="report-value"><span>Departments count</span><strong>${departmentsCount}</strong></div>
          </div>
          <button class="report-button" type="button">Generate Report</button>
        </div>

      </div>

      <div class="muted" style="margin-top:14px;">Tip: Report generation is coming soon.</div>
    </div>
  `;

  // Hook up report generators
  const buttons = root.querySelectorAll(".report-button");

  buttons[0].onclick = () => generateEquipmentReport(equipmentRows);
  buttons[1].onclick = () => generateSafetyReport(safetyRows);
  buttons[2].onclick = () => generateTicketReport(ticketRows);
  buttons[3].onclick = () => generateWorkforceReport(profileRows);
}

